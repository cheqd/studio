import type { Fixture, Step } from './engine.js';
import type { InventoryRoute } from './inventory.js';

export type CoverageStatus = 'recorded' | 'partly recorded' | 'to record' | 'no scenario step' | 'not recordable';

export interface CoverageRow {
	route: InventoryRoute;
	steps: string[];
	recorded: string[];
	status: CoverageStatus;
	note: string;
}

/** Why a route has no scenario step and is not expected to get one. */
function notRecordable(route: InventoryRoute): string | undefined {
	if (route.surface === 'internal') return 'internal route (redirect, static file, IdP webhook or session echo)';
	if (!route.inRouteTable) return 'in OpenAPI but not registered in the route table (documentation drift)';
	if (route.sideEffect === 'billing' && route.method !== 'GET')
		return 'mutates Stripe: record by hand against Stripe test mode';
	if (route.sensitive && route.method === 'POST' && route.path.startsWith('/did/export'))
		return 'returns private key material: record shape only by hand';
	return undefined;
}

export function computeCoverage(routes: InventoryRoute[], steps: Step[], fixtures: Fixture[]): CoverageRow[] {
	const recordedIds = new Set(fixtures.map((f) => f.stepId));
	return routes.map((route) => {
		const covering = steps.filter((s) => s.routeId === route.id).map((s) => s.id);
		const recorded = covering.filter((id) => recordedIds.has(id));
		let status: CoverageStatus;
		let note = '';
		if (covering.length === 0) {
			const reason = notRecordable(route);
			status = reason ? 'not recordable' : 'no scenario step';
			note = reason ?? '';
		} else if (recorded.length === covering.length) status = 'recorded';
		else if (recorded.length > 0) status = 'partly recorded';
		else status = 'to record';
		return { route, steps: covering, recorded, status, note };
	});
}

export function renderCoverage(rows: CoverageRow[]): string {
	const count = (pred: (r: CoverageRow) => boolean) => rows.filter(pred).length;
	const lines: string[] = [
		'# Contract coverage',
		'',
		'Generated by `npx tsx tests/contract/scripts/generate-coverage.ts`. Do not edit by hand.',
		'`inventory.test.ts` fails if this file is out of date.',
		'',
		`Routes: ${rows.length}. Tier 1: ${count((r) => r.route.tier === 1)}. Tier 2: ${count((r) => r.route.tier === 2)}.`,
		`Recorded: ${count((r) => r.status === 'recorded')}. Partly recorded: ${count((r) => r.status === 'partly recorded')}. ` +
			`To record: ${count((r) => r.status === 'to record')}. No scenario step yet: ${count((r) => r.status === 'no scenario step')}. ` +
			`Not recordable: ${count((r) => r.status === 'not recordable')}.`,
		'',
		'| Tier | Route | Auth | Side effect | Status | Steps | Note |',
		'|---|---|---|---|---|---|---|',
	];
	const sorted = [...rows].sort(
		(a, b) =>
			a.route.tier - b.route.tier ||
			a.route.path.localeCompare(b.route.path) ||
			a.route.method.localeCompare(b.route.method)
	);
	for (const r of sorted) {
		lines.push(
			`| ${r.route.tier} | \`${r.route.id}\` | ${r.route.auth} | ${r.route.sideEffect} | ${r.status} | ${r.steps.map((s) => `\`${s}\``).join(', ') || '-'} | ${r.note} |`
		);
	}
	return lines.join('\n') + '\n';
}
